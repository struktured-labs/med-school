"""Record the attract demo: a live copro-driven CPU-vs-CPU round (C port answers), per logic
frame inputs of both players, RLE-packed into src/demo_data.inc (b1, b2, run; run 0 = end)."""
import sys; sys.path[:0] = ["test", "ref"]
from vs import Rom, ROM, LAB, Copro
LV, SP, BOARDS, MAXRUNS = 4, 1, 0, 1900
best = None
for seed in [(0x3C, 0xA7), (0x52, 0x19), (0x7E, 0x44), (0x11, 0xD3), (0x9B, 0x60), (0xC4, 0x2F)]:
    r = Rom(ROM, LAB); r.start_game(LV, SP, *seed, mode=3, level2=LV, speed2=SP, boards=BOARDS)
    cop = Copro(r, 0); last = r.r("ticks"); inp = []
    for f in range(20000):
        r.step(0); cop.poll(None)
        t = r.r("ticks")
        if t != last:
            last = t; inp.append((r.r("P1::dbg_inp"), r.r("P2::dbg_inp")))
        if r.r("mstate") != 0: break
    runs = []
    for p in inp:
        if runs and runs[-1][:2] == list(p) and runs[-1][2] < 255: runs[-1][2] += 1
        else: runs.append([p[0], p[1], 1])
    final = (r.ram(0x400, 128), r.ram(0x500, 128))
    print("seed", seed, "frames", len(inp), "runs", len(runs), "done", r.r("mstate") != 0)
    if r.r("mstate") != 0 and len(runs) <= MAXRUNS and (best is None or len(inp) > best[1]):
        best = (seed, len(inp), runs, final)
seed, n, runs, final = best
with open("src/demo_data.inc", "w") as f:
    f.write("; generated by tools/mkdemo.py: recorded copro CPU-vs-CPU round, seed %02X%02X\n" % seed)
    f.write("DEMO_S0 = $%02X\nDEMO_S1 = $%02X\nDEMO_LV = %d\nDEMO_SP = %d\nDEMO_BOARDS = %d\nDEMO_FRAMES = %d\n" % (seed[0], seed[1], LV, SP, BOARDS, n))
    f.write("demo_data:\n")
    for i in range(0, len(runs), 8):
        f.write("  .byte " + ", ".join("$%02X,$%02X,%d" % tuple(x) for x in runs[i:i + 8]) + "\n")
    f.write("  .byte 0, 0, 0\n")
open("build/demo_final.txt", "w").write(repr(final))
print("chose", seed, n, "frames", len(runs), "runs")
